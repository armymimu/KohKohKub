/**
 * สร้างไฟล์หนังสือยินยอมแบบกระดาษ สำหรับพิมพ์ออกมาให้เจ้าของที่พักเซ็นตอนลงพื้นที่
 * ใช้ข้อความชุดเดียวกับในฟอร์มเว็บ แก้ที่ src/consent.js ที่เดียว
 *
 *   node scripts/make-consent-form.js
 */

require('dotenv').config();

const fs = require('fs');
const path = require('path');
const consent = require('../src/consent');
const config = require('../src/config');

const outDir = path.join(__dirname, '..', 'docs');
const outFile = path.join(outDir, 'consent-form.txt');

const form = `${consent.fullConsentText()}


ข้อมูลที่พัก (กรอกด้วยตัวบรรจง)

  ชื่อที่พัก ..............................................................................

  ธนาคาร ................................  เลขบัญชี ..................................

  ชื่อบัญชี ...............................................................................

  เบอร์โทร ..............................  เพจ Facebook ............................

  บริเวณ/หาด ..........................  พิกัด ......................................


ผู้ให้ความยินยอม

  ลงชื่อ ............................................  วันที่ ............................

  ชื่อ-นามสกุลตัวบรรจง .............................................................

  เกี่ยวข้องกับที่พักในฐานะ  [ ] เจ้าของ  [ ] ผู้จัดการ  [ ] ได้รับมอบหมาย

  แนบสำเนาบัตรประชาชน (ขีดคร่อมระบุ "ใช้สำหรับลงทะเบียนระบบตรวจสอบที่พักเท่านั้น")
  [ ] แนบแล้ว   [ ] ยังไม่แนบ


ผู้รับข้อมูล (เจ้าหน้าที่)

  ลงชื่อ ............................................  วันที่ ............................

  ชื่อ-นามสกุลตัวบรรจง .............................................................


เอกสารฉบับ ${config.consentVersion} — พิมพ์เมื่อ ${new Date().toISOString().slice(0, 10)}
ทำ 2 ฉบับ เก็บไว้กับผู้ดูแลระบบ 1 ฉบับ มอบให้เจ้าของที่พัก 1 ฉบับ
`;

fs.mkdirSync(outDir, { recursive: true });
// เขียนเป็น UTF-8 พร้อม BOM เพื่อให้ Notepad และ Word บน Windows อ่านภาษาไทยถูก
fs.writeFileSync(outFile, '﻿' + form, 'utf8');

console.log(`สร้างไฟล์แล้ว: ${outFile}`);
if (config.orgName.startsWith('[')) {
  console.log('');
  console.log('⚠️  ยังไม่ได้ตั้ง ORG_NAME / ORG_CONTACT ใน .env');
  console.log('    เอกสารจะมีช่องว่างที่ต้องเติมชื่อผู้ควบคุมข้อมูล');
}
