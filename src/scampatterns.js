/** คำที่บ่งบอกว่ากำลังหางาน/หารายได้ ใช้เสริมความมั่นใจของการจับรูปแบบ */
const INCOME_HINTS = [
  'งานเสริม', 'รายได้เสริม', 'หางาน', 'สมัครงาน', 'ทำงานที่บ้าน', 'work from home',
  'รับสมัครด่วน', 'ไม่ต้องมีประสบการณ์', 'วันละ', 'รายได้ดี', 'งานออนไลน์', 'พาร์ทไทม์',
];

/**
 * ตรวจว่าข้อความเข้าข่ายสแกมหารายได้แบบไหน
 * @returns {{type:string,label:string,mechanic:string[],matched:string[],incomeContext:boolean}|null}
 */
function detect(text) {
  const t = String(text || '').toLowerCase();
  if (!t) return null;

  const incomeContext = INCOME_HINTS.some((k) => t.includes(k.toLowerCase()));

  let best = null;
  for (const p of PATTERNS) {
    const matched = p.keywords.filter((k) => t.includes(k.toLowerCase()));
    if (!matched.length) continue;
    if (!best || matched.length > best.matched.length) {
      best = { ...p, matched, incomeContext };
    }
  }

  return best;
}

